"""프로모션 손익 계산 (화면 없이 계산만).

용어
- 1건 추정 기여액 = 본사 이익(공급 금액 × 매출총이익률) + 점주 잔여액
- 점주 잔여액 = 주문 금액 − 본사 공급 금액 − 배달비 부담 − 플랫폼 수수료 − 결제 수수료
- 본전 증분 비율 = 쿠폰 금액 ÷ 1건 추정 기여액
  (쿠폰 쓴 주문 100건 중 '쿠폰이 없었으면 안 생겼을 주문'이 몇 건 이상이어야 본전인지)
"""
import pandas as pd

기본가정 = {"주문금액": 25000, "공급금액": 10580, "배달비부담": 3400, "플랫폼수수료율": 7.8, "결제수수료율": 3.0}


def 건당구조(매출총이익률, 주문금액, 공급금액, 배달비부담, 플랫폼수수료율, 결제수수료율):
    본사 = 공급금액 * 매출총이익률
    플랫폼 = 주문금액 * 플랫폼수수료율 / 100
    결제 = 주문금액 * 결제수수료율 / 100
    점주 = 주문금액 - 공급금액 - 배달비부담 - 플랫폼 - 결제
    return {"본사 이익": 본사, "점주 잔여액": 점주, "추정 기여액": 본사 + 점주,
            "플랫폼 수수료": 플랫폼, "결제 수수료": 결제}


def 본전표(구조, 쿠폰들=(1000, 2000, 3000, 5000), 본사부담=50):
    rows = []
    for c in 쿠폰들:
        전체 = c / 구조["추정 기여액"] * 100
        본사 = (c * 본사부담 / 100) / 구조["본사 이익"] * 100 if 구조["본사 이익"] > 0 else None
        rows.append({"쿠폰 금액": c,
                     "본전 증분 비율(본사+점주)": 전체,
                     f"본전 증분 비율(본사만, 부담 {본사부담:.0f}%)": 본사})
    return pd.DataFrame(rows)


def 행사계산(주문수, 사용률, 증분주문, 쿠폰, 기여액, 본사이익, 변동비=0, 본사부담=50, 플랫폼지원=0):
    """주문수 = 행사 기간 전체 주문, 사용률 % = 그중 쿠폰 쓴 비율, 증분주문 = 행사로 새로 생긴 주문 수."""
    사용주문 = 주문수 * 사용률 / 100
    순할인 = max(쿠폰 - 플랫폼지원, 0)
    할인비 = 사용주문 * 순할인
    증분이익 = 증분주문 * (기여액 - 변동비)
    손익 = 증분이익 - 할인비
    증분비율 = 증분주문 / 사용주문 * 100 if 사용주문 else 0
    기준 = 순할인 / (기여액 - 변동비) * 100 if 기여액 > 변동비 else float("inf")
    본사손익 = 증분주문 * 본사이익 - 할인비 * 본사부담 / 100
    점주손익 = 손익 - 본사손익
    if 손익 > 0 and 증분비율 >= 기준 * 1.3:
        판단 = "확대"
    elif 손익 >= 0:
        판단 = "유지·조정"
    elif 증분비율 >= 기준 * 0.6:
        판단 = "조정"
    else:
        판단 = "중단 검토"
    return {"쿠폰 사용 주문": 사용주문, "할인비": 할인비, "1건당 할인비": 할인비 / 주문수 if 주문수 else 0,
            "증분 이익": 증분이익, "손익": 손익, "증분 비율": 증분비율, "본전 기준": 기준,
            "본사 손익": 본사손익, "점주 손익": 점주손익, "판단": 판단}


def 민감도(주문수, 증분주문, 쿠폰, 기여액, 플랫폼지원=0, 사용률들=(10, 20, 30, 40, 50), 변동비들=(0, 1000, 2000, 3000, 5000)):
    """행 = 쿠폰 사용률, 열 = 매장 추가 변동비. 값 = 행사 손익(원)."""
    t = {}
    for v in 변동비들:
        t[f"변동비 {v:,}원"] = [행사계산(주문수, u, 증분주문, 쿠폰, 기여액, 0, v, 0, 플랫폼지원)["손익"] for u in 사용률들]
    return pd.DataFrame(t, index=[f"사용률 {u}%" for u in 사용률들])
